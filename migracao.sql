-- 4) Perfis de acesso
create table if not exists profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('admin','boat')),
  boat_id bigint references boats(id)
);
create or replace function is_admin() returns boolean language sql security definer stable set search_path = public as
$$ select exists (select 1 from profiles where id = auth.uid() and role = 'admin') $$;
create or replace function my_boat() returns bigint language sql security definer stable set search_path = public as
$$ select boat_id from profiles where id = auth.uid() $$;

-- 5) Segurança: troca as regras antigas de categories/products pelas novas
do $$ declare r record; begin
  for r in select policyname, tablename from pg_policies
           where schemaname = 'public' and tablename in ('categories','products','boats','profiles')
  loop execute format('drop policy %I on public.%I', r.policyname, r.tablename); end loop;
end $$;

alter table boats enable row level security;
alter table categories enable row level security;
alter table products enable row level security;
alter table profiles enable row level security;

create policy "ler barcos" on boats for select using (active or is_admin() or id = my_boat());
create policy "editar barco" on boats for update using (is_admin() or id = my_boat()) with check (is_admin() or id = my_boat());
create policy "ler categorias" on categories for select using (active);
create policy "ler produtos" on products for select using (active);
create policy "editar categorias" on categories for all using (is_admin() or boat_id = my_boat()) with check (is_admin() or boat_id = my_boat());
create policy "editar produtos" on products for all using (is_admin() or boat_id = my_boat()) with check (is_admin() or boat_id = my_boat());
create policy "ver meu perfil" on profiles for select using (id = auth.uid());

